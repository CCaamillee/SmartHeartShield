_CLINICAL_REPLACEMENTS = tuple(
    sorted(CLINICAL_PHRASES.items(), key=lambda item: len(item[0]), reverse=True)
)
_HAN_RE = re.compile(r"[\u3400-\u9fff]+")


@lru_cache(maxsize=16_384)
def _translate_clinical_text(text: str) -> str:
    translated = text.replace("#!#", "; ").replace("；", "; ")
    translated = translated.replace("（", " (").replace("）", ")")
    translated = translated.replace("，", ", ").replace("。", ". ").replace("：", ": ")
    for source, target in _CLINICAL_REPLACEMENTS:
        translated = translated.replace(source, target)
    translated = re.sub(r"(Killip|NYHA)\s*([ⅠⅡⅢⅣIVX]+)\s*级", r"\1 class \2", translated, flags=re.I)
    translated = re.sub(r"([ⅠⅡⅢⅣIVX]+)\s*级", r"grade \1", translated)
    translated = re.sub(r"(\d+)\s*岁", r"\1 years", translated)
    translated = re.sub(r"(\d+)\s*天", r"\1 days", translated)
    if _HAN_RE.search(translated):
        translated = _HAN_RE.sub(" additional clinical detail ", translated)
    translated = re.sub(r"(?<=[A-Za-z])(?=grade\b)", " ", translated)
    translated = re.sub(r"(?<=\d)\.(?=[A-Za-z])", ". ", translated)
    translated = re.sub(r"\s+([,.;:)])", r"\1", translated)
    translated = re.sub(r"([(])\s+", r"\1", translated)
    translated = re.sub(r"\s{2,}", " ", translated).strip(" ;,")
    translated = re.sub(
        r"(?:additional clinical detail\s*){2,}",
        "additional clinical detail ",
        translated,
        flags=re.I,
    ).strip()
    return translated or "No record"


