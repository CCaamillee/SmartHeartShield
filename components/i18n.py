def field_label(value: object) -> str:
    text = str(value or "").strip()
    if text in FIELD_LABELS:
        return FIELD_LABELS[text]
    match = re.fullmatch(r"(.+)_([23])", text)
    if match and match.group(1) in FIELD_LABELS:
        return f"{FIELD_LABELS[match.group(1)]} — Set {match.group(2)}"
    return ui_text(text)


